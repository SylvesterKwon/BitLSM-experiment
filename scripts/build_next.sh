#!/usr/bin/env bash
# Build NEXT's isolated RocksDB 7.7.3 static lib + (later) the next driver.
# Kept fully separate from the experiment CMake (which uses RocksDB 10.10.0).
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
next_root="${repo_root}/third_party/NEXT"
rocksdb_src="${next_root}/rocksdb-7.7.3"
jobs="$(nproc)"

if [[ ! -d "${rocksdb_src}" ]]; then
  echo "ERROR: submodule not initialized. Run: git submodule update --init third_party/NEXT" >&2
  exit 1
fi

# Apply patches/next-multiattr.patch to the NEXT rocksdb submodule, idempotently.
patch_file="${repo_root}/patches/next-multiattr.patch"
if [[ -s "${patch_file}" ]]; then
  if git -C "${rocksdb_src}" apply --reverse --check "${patch_file}" 2>/dev/null; then
    echo "[build_next] next-multiattr patch already applied"
  elif git -C "${rocksdb_src}" apply --check "${patch_file}" 2>/dev/null; then
    git -C "${rocksdb_src}" apply "${patch_file}"; echo "[build_next] applied next-multiattr patch"
  else
    echo "[build_next] ERROR: next-multiattr.patch does not apply cleanly" >&2
    git -C "${rocksdb_src}" apply --check "${patch_file}"
    exit 1
  fi
else
  echo "[build_next] no next-multiattr patch to apply"
fi

echo "[build_next] building NEXT librocksdb.a (this takes several minutes)..."
make -C "${rocksdb_src}" -j"${jobs}" static_lib

echo "[build_next] done: ${rocksdb_src}/librocksdb.a"
ls -la "${rocksdb_src}/librocksdb.a"

driver_out="${repo_root}/build/bin"
mkdir -p "${driver_out}"

echo "[build_next] building next_smoke (unmodified NEXT num-write example)..."
# Mirror examples/Makefile link line: -fno-rtti, link librocksdb.a + platform libs.
# make_config.mk (generated by the lib build) holds PLATFORM_* flags in *make*
# syntax with unquoted, multi-word values, so bash cannot `source` it as shell
# assignments. Extract the exact flag strings and pass them to g++ verbatim.
# PLATFORM_CXXFLAGS carries the RocksDB platform defines (-DROCKSDB_PLATFORM_POSIX
# etc.) that the internal headers require, plus -march=native to match librocksdb.a.
mk="${rocksdb_src}/make_config.mk"
PLATFORM_CXXFLAGS="$(grep -m1 '^PLATFORM_CXXFLAGS=' "${mk}" | cut -d= -f2-)"
PLATFORM_LDFLAGS="$(grep -m1 '^PLATFORM_LDFLAGS=' "${mk}" | cut -d= -f2-)"
EXEC_LDFLAGS="$(grep -m1 '^EXEC_LDFLAGS=' "${mk}" | cut -d= -f2-)"
g++ -std=c++17 -fno-rtti -O2 \
  "${rocksdb_src}/examples/secondary_index_data_write_num.cc" \
  -o "${driver_out}/next_smoke" \
  -I"${rocksdb_src}/include" -I"${rocksdb_src}" \
  ${PLATFORM_CXXFLAGS} \
  "${rocksdb_src}/librocksdb.a" \
  ${PLATFORM_LDFLAGS} ${EXEC_LDFLAGS} \
  -lpthread -ldl -lz -lbz2 -lsnappy -llz4 -lzstd
echo "[build_next] done: ${driver_out}/next_smoke"

# nlohmann/json single header (pinned), cached under a gitignored deps dir
json_hpp="${repo_root}/third_party/next_deps/json.hpp"
if [[ ! -f "${json_hpp}" ]]; then
  mkdir -p "$(dirname "${json_hpp}")"
  echo "[build_next] fetching nlohmann/json.hpp (v3.11.3)..."
  curl -fsSL -o "${json_hpp}" \
    https://github.com/nlohmann/json/releases/download/v3.11.3/json.hpp
fi

echo "[build_next] building next_honk driver..."
g++ -std=c++17 -fno-rtti -O2 \
  "${repo_root}/src/next_driver/next_honk.cpp" \
  -o "${driver_out}/next_honk" \
  -I"${rocksdb_src}/include" -I"${rocksdb_src}" \
  -I"$(dirname "${json_hpp}")" -I"${repo_root}/src/honk_player" -I"${repo_root}/src/next_driver" \
  "${rocksdb_src}/librocksdb.a" \
  ${PLATFORM_CXXFLAGS:-} ${PLATFORM_LDFLAGS:-} ${EXEC_LDFLAGS:-} \
  -lpthread -ldl -lz -lbz2 -lsnappy -llz4 -lzstd
echo "[build_next] done: ${driver_out}/next_honk"
